// ♻️ Volta um backup (.json.gz do Admin → Loja → Backup) num banco VAZIO
// Uso: node scripts/restore-backup.js backup-2026-10-20-0815.json.gz
// Usa as mesmas variáveis DB_* do servidor. Se alguma tabela já tiver dados, não mexe em nada.
const fs = require('fs');
const zlib = require('zlib');
const pool = require('../src/utils/database');

const q = (name) => `"${name.replace(/"/g, '""')}"`;

const main = async () => {
  const file = process.argv[2];
  if (!file) throw new Error('Informe o arquivo: node scripts/restore-backup.js backup-....json.gz');
  const backup = JSON.parse(zlib.gunzipSync(fs.readFileSync(file)).toString('utf8'));
  if (backup.app !== 'emporio-brumado' || !backup.schema || !backup.data) throw new Error('Esse arquivo não é um backup do Empório');
  const { tables, sequences } = backup.schema;

  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    for (const s of sequences) {
      await client.query(`CREATE SEQUENCE IF NOT EXISTS ${q(s.name)} AS ${s.data_type} START ${s.start_value} INCREMENT ${s.increment_by}`);
    }

    const constraintExists = async (table, name) => (await client.query(
      'SELECT 1 FROM pg_constraint WHERE conname = $1 AND conrelid = $2::regclass', [name, q(table)]
    )).rowCount > 0;

    // Tabelas, colunas e chaves (as ligações entre tabelas entram depois dos dados)
    for (const t of tables) {
      const identity = { a: ' GENERATED ALWAYS AS IDENTITY', d: ' GENERATED BY DEFAULT AS IDENTITY' };
      const cols = t.columns.map(c => `${q(c.name)} ${c.type}${c.default ? ` DEFAULT ${c.default}` : ''}${identity[c.identity] || ''}${c.not_null ? ' NOT NULL' : ''}`);
      await client.query(`CREATE TABLE IF NOT EXISTS ${q(t.name)} (${cols.join(', ')})`);
      for (const c of cols) await client.query(`ALTER TABLE ${q(t.name)} ADD COLUMN IF NOT EXISTS ${c}`);
      const { rows } = await client.query(`SELECT EXISTS (SELECT 1 FROM ${q(t.name)}) AS has`);
      if (rows[0].has) throw new Error(`A tabela ${t.name} já tem dados. Use um banco vazio.`);
      for (const k of t.constraints.filter(k => k.kind !== 'f')) {
        if (!(await constraintExists(t.name, k.name))) await client.query(`ALTER TABLE ${q(t.name)} ADD CONSTRAINT ${q(k.name)} ${k.def}`);
      }
    }

    // Dados
    for (const t of tables) {
      const rows = backup.data[t.name] || [];
      if (!rows.length) continue;
      const json = new Set(t.columns.filter(c => /^jsonb?$/.test(c.type)).map(c => c.name));
      const names = t.columns.map(c => c.name);
      for (let i = 0; i < rows.length; i += 500) {
        const chunk = rows.slice(i, i + 500);
        const values = [];
        const tuples = chunk.map(r => `(${names.map(n => {
          const v = r[n] === undefined ? null : r[n];
          values.push(json.has(n) && v !== null ? JSON.stringify(v) : v);
          return `$${values.length}`;
        }).join(', ')})`);
        await client.query(`INSERT INTO ${q(t.name)} (${names.map(q).join(', ')}) OVERRIDING SYSTEM VALUE VALUES ${tuples.join(', ')}`, values);
      }
      console.log(`✔ ${t.name}: ${rows.length}`);
    }

    // Ligações entre tabelas e índices
    for (const t of tables) {
      for (const k of t.constraints.filter(k => k.kind === 'f')) {
        if (!(await constraintExists(t.name, k.name))) await client.query(`ALTER TABLE ${q(t.name)} ADD CONSTRAINT ${q(k.name)} ${k.def}`);
      }
      for (const def of t.indexes) {
        await client.query(def.replace(/^CREATE (UNIQUE )?INDEX /, 'CREATE $1INDEX IF NOT EXISTS '));
      }
    }

    // Numeração continua de onde parou (próximo pedido, próximo produto...)
    const serials = (await client.query(
      `SELECT table_name, column_name,
              COALESCE(substring(column_default from 'nextval\\(''([^'']+)'''), pg_get_serial_sequence(quote_ident(table_name), column_name)) AS seq
       FROM information_schema.columns WHERE table_schema = 'public' AND (column_default LIKE 'nextval(%' OR is_identity = 'YES')`
    )).rows;
    for (const s of serials) {
      if (!s.seq) continue;
      await client.query(`ALTER SEQUENCE ${s.seq} OWNED BY ${q(s.table_name)}.${q(s.column_name)}`);
      await client.query(
        `SELECT setval($1, COALESCE((SELECT MAX(${q(s.column_name)}) FROM ${q(s.table_name)}), 0) + 1, false)`, [s.seq]
      );
    }

    await client.query('COMMIT');
    console.log(`✅ Backup de ${backup.created_at} restaurado`);
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
};

main()
  .catch(err => { console.error('❌', err.message); process.exitCode = 1; })
  .finally(() => pool.end());
